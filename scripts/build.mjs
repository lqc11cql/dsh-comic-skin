/**
 * Builds the browser module: src/client.template.js with the stylesheet from
 * src/theme.css inlined as a string literal. Run with `node scripts/build.mjs`
 * from the package directory; the generated client.js is the shipped artifact.
 */
import { readFileSync, writeFileSync } from 'node:fs'

const root = new URL('../', import.meta.url)
const css = readFileSync(new URL('src/theme.css', root), 'utf8')
const template = readFileSync(new URL('src/client.template.js', root), 'utf8')
const marker = '__THEME_CSS__'

if (!template.includes(marker)) throw new Error(`template is missing ${marker}`)

const banner = `/* Generated by scripts/build.mjs — edit src/theme.css or src/client.template.js instead. */\n`
const output = banner + template.replace(marker, () => JSON.stringify(css))

writeFileSync(new URL('client.js', root), output)
console.log(`client.js written (${output.length} bytes)`)
